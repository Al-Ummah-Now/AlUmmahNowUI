/**
 * Writes the environment-specific files into dist/ after `astro build`:
 *   robots.txt   production: Allow / and the sitemap; QA, stage and local: Disallow: /
 *   _headers     security headers on every response (Workers static assets apply them), long
 *                caching for hashed assets, and X-Robots-Tag: noindex, nofollow off production
 *   _redirects   / → /en/ (302: the language is a choice, never a permanent answer)
 *
 *   node --experimental-strip-types scripts/env-files.ts --env qa|stage|production|local [--dist dir]
 *
 * The release builds once and runs this per environment on the same dist/ (wiki AUN-DEV-SITE §Hosting).
 */
import { writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ENVIRONMENTS, PRODUCTION_ORIGIN, parseEnvArg, type BuildEnv } from './environments.ts';

/**
 * Nothing on the site is inline or third-party: scripts, styles and fonts are files on this origin.
 * The one exception is Cloudflare Web Analytics, which Cloudflare injects at the edge: its beacon
 * script and the address it reports to are allowed exactly, as www allows them (apps/www/src/lib/edge.ts).
 * Forms post nowhere (Contact links to the videos site's form), so form-action is 'none'.
 */
export const CF_ANALYTICS_SCRIPT = 'https://static.cloudflareinsights.com';
export const CF_ANALYTICS_CONNECT = 'https://cloudflareinsights.com';
export const CSP = [
  "default-src 'none'",
  `script-src 'self' ${CF_ANALYTICS_SCRIPT}`,
  "style-src 'self'",
  "img-src 'self'",
  "font-src 'self'",
  `connect-src 'self' ${CF_ANALYTICS_CONNECT}`,
  "manifest-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
].join('; ');

export function indexable(env: BuildEnv): boolean {
  return env !== 'local' && ENVIRONMENTS[env].indexable;
}

export function robotsTxt(env: BuildEnv): string {
  if (!indexable(env)) return 'User-agent: *\nDisallow: /\n';
  return `User-agent: *\nAllow: /\n\nSitemap: ${PRODUCTION_ORIGIN}/sitemap.xml\n`;
}

export function headersFile(env: BuildEnv): string {
  const all = [
    `Content-Security-Policy: ${CSP}`,
    'X-Content-Type-Options: nosniff',
    'Referrer-Policy: strict-origin-when-cross-origin',
    'Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()',
    'Cross-Origin-Opener-Policy: same-origin',
    'Strict-Transport-Security: max-age=31536000',
  ];
  if (!indexable(env)) all.push('X-Robots-Tag: noindex, nofollow');
  const block = (path: string, lines: string[]) => `${path}\n${lines.map((l) => `  ${l}`).join('\n')}\n`;
  return [
    '# Generated by scripts/env-files.ts. Do not edit.',
    block('/*', all),
    // Astro's hashed bundles never change under the same name
    block('/_astro/*', ['Cache-Control: public, max-age=31536000, immutable']),
    block('/fonts/*', ['Cache-Control: public, max-age=604800, stale-while-revalidate=2592000']),
    block('/brand/*', ['Cache-Control: public, max-age=86400, stale-while-revalidate=604800']),
    block('/icons/*', ['Cache-Control: public, max-age=86400, stale-while-revalidate=604800']),
  ].join('\n');
}

export const REDIRECTS = '/ /en/ 302\n';

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  const env = parseEnvArg(argv, true);
  const d = argv.indexOf('--dist');
  const dist = resolve(d >= 0 && argv[d + 1] ? argv[d + 1]! : fileURLToPath(new URL('../dist', import.meta.url)));
  if (!existsSync(resolve(dist, 'en/index.html'))) {
    process.stderr.write(`FAIL  ${dist} has no en/index.html: run astro build first\n`);
    process.exit(1);
  }
  writeFileSync(resolve(dist, 'robots.txt'), robotsTxt(env));
  writeFileSync(resolve(dist, '_headers'), headersFile(env));
  writeFileSync(resolve(dist, '_redirects'), REDIRECTS);
  process.stdout.write(`env files for ${env}: robots.txt (${indexable(env) ? 'indexable' : 'noindex'}), _headers, _redirects\n`);
}
