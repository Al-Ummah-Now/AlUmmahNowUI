/**
 * Vendors the shared post format, PostV2 (AlUmmahNow `packages/shared-types/src/post-schema.ts`; wiki
 * AUN-SCHOLAR-SITES §6.3), into `packages/render/src/posts/post-schema.generated.ts` (shared with the sites Worker) at a pinned commit, and records the
 * source's sha256 in `post-schema.lock.json`. The same file is vendored by AlUmmahNowCMS, so the CMS,
 * www and the videos platform agree on kinds, limits, validation and the summary.
 *
 *   node --experimental-strip-types scripts/sync-posts.ts --ref <sha>   (fetch, write, lock)
 *   node --experimental-strip-types scripts/sync-posts.ts --check       (offline: file == lock)
 *
 * The monorepo is public: the file comes from raw.githubusercontent.com with no token.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const REPO = "Al-Ummah-Now/AlUmmahNow";
const PATH = "packages/shared-types/src/post-schema.ts";
const LOCK = "post-schema.lock.json";
const OUT = "../../packages/render/src/posts/post-schema.generated.ts";

interface Lock {
   repo: string;
   ref: string;
   path: string;
   sha256: string;
}

const sha256 = (s: string) => createHash("sha256").update(s).digest("hex");
const header = (ref: string) => `// Generated by scripts/sync-posts.ts from ${REPO}@${ref}:${PATH}. Do not edit.\n`;

/** The vendored source without its generated header. */
export function sourceOf(vendored: string): string {
   const nl = vendored.indexOf("\n");
   return vendored.startsWith("// Generated by scripts/sync-posts.ts") && nl >= 0 ? vendored.slice(nl + 1) : vendored;
}

function check(): void {
   const lock = JSON.parse(readFileSync(LOCK, "utf8")) as Lock;
   const file = readFileSync(OUT, "utf8");
   if (!file.startsWith(header(lock.ref))) throw new Error(`${OUT}: header does not name ${lock.ref}; run npm run sync:posts -- --ref ${lock.ref}`);
   const got = sha256(sourceOf(file));
   if (got !== lock.sha256) throw new Error(`${OUT} differs from ${REPO}@${lock.ref}:${PATH} (sha256 ${got} ≠ ${lock.sha256}). Never edit it by hand: change the monorepo, then npm run sync:posts -- --ref <sha>.`);
   console.log(`check:posts: OK (${REPO}@${lock.ref.slice(0, 12)})`);
}

async function sync(ref: string): Promise<void> {
   if (!/^[0-9a-f]{40}$/.test(ref)) throw new Error("--ref must be a full commit sha");
   const url = `https://raw.githubusercontent.com/${REPO}/${ref}/${PATH}`;
   const res = await fetch(url);
   if (!res.ok) throw new Error(`${url}: ${res.status}`);
   const text = await res.text();
   if (/^\s*import\s/m.test(text)) throw new Error("post-schema.ts must stay self-contained (no imports)");
   writeFileSync(OUT, header(ref) + text);
   const lock: Lock = { repo: REPO, ref, path: PATH, sha256: sha256(text) };
   writeFileSync(LOCK, `${JSON.stringify(lock, null, 2)}\n`);
   console.log(`sync:posts: ${OUT} ← ${REPO}@${ref.slice(0, 12)}`);
}

const args = process.argv.slice(2);
if (args.includes("--check")) check();
else {
   const i = args.indexOf("--ref");
   await sync(i >= 0 ? (args[i + 1] ?? "") : "");
}
