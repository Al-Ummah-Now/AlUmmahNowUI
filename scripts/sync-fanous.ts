/**
 * Vendors the site themes of the videos app (AlUmmahNow `apps/web/src/theme/site-themes.css`,
 * generated there from the built-in Fanous theme packages) into www at a pinned commit, so www
 * uses the same design tokens as the videos app and never hand-copies a colour.
 *
 *   node --experimental-strip-types scripts/sync-fanous.ts --ref <40-char sha>   (fetch, rewrite)
 *   node --experimental-strip-types scripts/sync-fanous.ts                       (re-fetch the locked ref)
 *   node --experimental-strip-types scripts/sync-fanous.ts --check               (offline: outputs == lock)
 *
 * The monorepo is public: files come from raw.githubusercontent.com with no token.
 *
 * The videos app marks dark with `html.dark`; www follows the system setting with no JS and
 * forces a choice with `html[data-mode]` (src/lib/theme-mode.ts). So for each theme:
 *   - the base and light blocks become `html[data-theme='<id>']`
 *   - the dark block becomes `html[data-theme='<id>'][data-mode='dark']` and, inside
 *     `@media (prefers-color-scheme: dark)`, `html[data-theme='<id>']:not([data-mode='light'])`
 * (both one attribute more specific than the light block, so order does not matter).
 * The lantern street's tokens (--fanous-street-*) are always kept, and the shared street module
 * (packages/fanous-tokens/street) is vendored at the same commit into src/lib and src/styles.
 * Only the tokens www uses are kept: those named in USED_IN (src/styles/global.css) and in the shared
 * nav stylesheet, plus the header colour for meta theme-color. Colours and the per-theme scales
 * (radius, spacing, elevation, duration) are kept; type and brand scales are not.
 *
 * The shared nav contract (AlUmmahNow docs/design/NAV.md, `packages/fanous-tokens/nav/aun-nav.css`)
 * is vendored as is, at the same commit, into NAV_OUT: the header account button and menus look
 * the same in every Al Ummah Now app. tests/site-theme.test.ts fails when global.css uses a token
 * the generated file lacks (run the sync again).
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const REPO = 'Al-Ummah-Now/AlUmmahNow';
const SOURCE = 'apps/web/src/theme/site-themes.css';
const LOCK = 'fanous.lock.json';
export const CSS_OUT = 'src/styles/fanous-themes.generated.css';
export const TS_OUT = 'src/lib/site-themes.generated.ts';
export const USED_IN = 'src/styles/global.css';
const NAV_SOURCE = 'packages/fanous-tokens/nav/aun-nav.css';
export const NAV_OUT = 'src/styles/aun-nav.generated.css';
/** The account menu's app icons (each app's own favicon, 96 px lossless WebP): separate files, served as is. */
export const NAV_ICON_IDS = ['www', 'videos', 'profile', 'cms', 'admin', 'auth-admin'] as const;
const NAV_ICON_SOURCE = 'packages/fanous-tokens/nav/icons';
export const NAV_ICON_OUT = 'public/aun-nav/icons';
/** The videos app's default (shared-types DEFAULT_SITE_THEME): rendered when the admin's answer cannot be used. */
const DEFAULT_THEME = 'fawanees';

interface Lock {
  repo: string;
  ref: string;
  source: string;
  sourceSha256: string;
  /** The street module's source files at the same ref, by path. */
  street?: Record<string, string>;
  outputs: Record<string, string>;
}

/** A vendored street module file: the source as is, under a generated-file header. */
export function vendorStreetFile(source: string, path: string, ref: string, kind: 'js' | 'dts' | 'css'): string {
  const header = `Generated by scripts/sync-fanous.ts from ${REPO}@${ref}:${path}. Do not edit.`;
  return `${kind === 'css' ? `/* ${header} */` : `// ${header}`}\n${source}`;
}

const sha256 = (s: string | Uint8Array) => createHash('sha256').update(s).digest('hex');

type Part = 'base' | 'light' | 'dark';
export interface ThemeBlocks {
  base: string[];
  light: string[];
  dark: string[];
}

const KEEP = /^--fanous-(brand|color|c|radius|spacing|elevation|duration|street)-[a-z0-9-]+$/;
/** The lantern street's tokens: always kept (the vendored street module reads them, not global.css). */
const STREET = /^--fanous-street-[a-z0-9-]+$/;
/** The street's lights are the one value that may hold a URL: an inline SVG (data:), never a fetch. */
const LIGHTS = /^url\("data:image\/svg\+xml,[A-Za-z0-9%._~!*'()-]+"\)$/;
/** The shared street module, vendored at the same commit (packages/fanous-tokens/street). */
export const STREET_SOURCES = { js: 'packages/fanous-tokens/street/fanous-street.js', dts: 'packages/fanous-tokens/street/fanous-street.d.ts', css: 'packages/fanous-tokens/street/fanous-street.css' } as const;
export const STREET_JS_OUT = 'src/lib/fanous-street.generated.js';
export const STREET_CSS_OUT = 'src/styles/fanous-street.generated.css';
export const STREET_DTS_OUT = 'src/lib/fanous-street.generated.d.ts';
const THEMED = /^html\[data-theme='([a-z][a-z0-9-]*)'\](\.dark|:not\(\.dark\))?$/;
/** Selectors for an unthemed page (the videos app's fallback); www always sets data-theme. */
const UNTHEMED = new Set([':root', '.dark', 'html:not(.dark)']);

/** The --fanous-* tokens a stylesheet reads. */
export function usedTokens(css: string): Set<string> {
  return new Set([...css.matchAll(/var\((--fanous-[a-z0-9-]+)/g)].map((m) => m[1]!));
}

/** Top-level rules of a stylesheet, comments removed; at-rules (reduced motion) are skipped. */
function rules(css: string): { selector: string; body: string }[] {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const out: { selector: string; body: string }[] = [];
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf('{', i);
    if (open < 0) break;
    const selector = text.slice(i, open).trim();
    let depth = 1;
    let j = open + 1;
    for (; j < text.length && depth > 0; j++) {
      if (text[j] === '{') depth++;
      else if (text[j] === '}') depth--;
    }
    if (depth !== 0) throw new Error(`unbalanced braces after "${selector}"`);
    if (!selector.startsWith('@')) out.push({ selector, body: text.slice(open + 1, j - 1) });
    i = j;
  }
  return out;
}

/** The colour declarations of each theme, by part. Throws on any selector it does not understand. */
export function parseThemes(css: string): Map<string, ThemeBlocks> {
  const themes = new Map<string, ThemeBlocks>();
  for (const { selector, body } of rules(css)) {
    const decls = body
      .split(';')
      .map((d) => d.trim())
      .filter(Boolean)
      .map((d) => {
        const colon = d.indexOf(':');
        if (colon < 0) throw new Error(`bad declaration in "${selector}": ${d}`);
        return [d.slice(0, colon).trim(), d.slice(colon + 1).trim()] as const;
      })
      .filter(([name]) => KEEP.test(name))
      .map(([name, value]) => {
        const lights = name === '--fanous-street-lights' && LIGHTS.test(value);
        if (!lights && /[<>{}]|url\(|expression/i.test(value)) throw new Error(`unexpected value for ${name}: ${value}`);
        return `${name}:${value}`;
      });
    for (const sel of selector.split(',').map((s) => s.trim())) {
      if (UNTHEMED.has(sel)) continue;
      const m = THEMED.exec(sel);
      if (!m) throw new Error(`unexpected selector in ${SOURCE}: ${sel}`);
      const id = m[1]!;
      const part: Part = m[2] === '.dark' ? 'dark' : m[2] ? 'light' : 'base';
      const blocks = themes.get(id) ?? { base: [], light: [], dark: [] };
      blocks[part].push(...decls);
      themes.set(id, blocks);
    }
  }
  for (const [id, b] of themes) {
    for (const part of ['base', 'light', 'dark'] as const) {
      if (!b[part].length) throw new Error(`theme ${id} has no ${part} colours`);
    }
  }
  return themes;
}

/** The last value a block gives a token (blocks are emitted in order, so the last wins). */
function value(decls: string[], name: string): string {
  const hit = decls.filter((d) => d.startsWith(`${name}:`)).pop();
  if (!hit) throw new Error(`missing ${name}`);
  return hit.slice(name.length + 1);
}

export function buildOutputs(css: string, ref: string, used: Set<string>): { css: string; ts: string } {
  const all = parseThemes(css);
  const keep = (decls: string[]) => decls.filter((d) => { const name = d.slice(0, d.indexOf(':')); return used.has(name) || STREET.test(name); });
  const themes = new Map([...all].map(([id, b]) => [id, { base: keep(b.base), light: keep(b.light), dark: keep(b.dark) }]));
  for (const name of used) {
    for (const [id, b] of all) {
      if (![...b.base, ...b.light].some((d) => d.startsWith(`${name}:`))) throw new Error(`${USED_IN} or ${NAV_OUT} uses ${name}, which theme ${id} does not define`);
    }
  }
  const ids = [...themes.keys()];
  if (!ids.includes(DEFAULT_THEME)) throw new Error(`default theme ${DEFAULT_THEME} is not in ${SOURCE}`);
  const header = `Generated by scripts/sync-fanous.ts from ${REPO}@${ref}:${SOURCE}. Do not edit.`;
  let outCss = `/* ${header} */\n`;
  let dark = '';
  for (const [id, b] of themes) {
    const sel = `html[data-theme='${id}']`;
    outCss += `${sel}{${[...b.base, ...b.light].join(';')}}\n`;
    outCss += `${sel}[data-mode='dark']{${b.dark.join(';')}}\n`;
    dark += `${sel}:not([data-mode='light']){${b.dark.join(';')}}\n`;
  }
  outCss += `@media (prefers-color-scheme: dark){\n${dark}}\n`;
  // Browser chrome (meta theme-color): the header's colour, which is dark in every theme
  const chrome = Object.fromEntries(
    [...all].map(([id, b]) => [id, { light: value(b.light, '--fanous-c-nav-bg'), dark: value(b.dark, '--fanous-c-nav-bg') }]),
  );
  const ts =
    `// ${header}\n` +
    `export const THEME_IDS = ${JSON.stringify(ids)} as const;\n` +
    `export type ThemeId = (typeof THEME_IDS)[number];\n` +
    `export const DEFAULT_THEME: ThemeId = ${JSON.stringify(DEFAULT_THEME)};\n` +
    `/** meta theme-color per theme and scheme (the header colour, --fanous-c-nav-bg). */\n` +
    `export const THEME_CHROME: Record<ThemeId, { light: string; dark: string }> = ${JSON.stringify(chrome, null, 2)};\n`;
  return { css: outCss, ts };
}

/** The shared nav stylesheet as is, under a generated-file header. */
export function navOutput(css: string, ref: string): string {
  // Nothing is fetched or inlined from the stylesheet: the app icons are separate files (NAV_ICON_OUT)
  if (/@import|url\(|expression/i.test(css)) throw new Error(`${NAV_SOURCE}: unexpected @import, url() or expression`);
  return `/* Generated by scripts/sync-fanous.ts from ${REPO}@${ref}:${NAV_SOURCE}. Do not edit. */\n${css}`;
}

async function main() {
  const args = process.argv.slice(2);
  const arg = (name: string) => {
    const i = args.indexOf(name);
    return i >= 0 ? args[i + 1] : undefined;
  };
  let lock: Lock | undefined;
  try {
    lock = JSON.parse(readFileSync(LOCK, 'utf8')) as Lock;
  } catch {
    lock = undefined;
  }
  if (args.includes('--check')) {
    if (!lock) throw new Error(`${LOCK} is missing`);
    for (const [file, hash] of Object.entries(lock.outputs)) {
      if (sha256(readFileSync(file)) !== hash) {
        console.error(`${file} does not match ${LOCK} (hand edit?). Run: npm run sync:fanous`);
        process.exit(1);
      }
    }
    console.log(`fanous: generated files match the lock (${REPO}@${lock.ref.slice(0, 8)})`);
    return;
  }
  const ref = arg('--ref') ?? lock?.ref;
  if (!ref || !/^[0-9a-f]{40}$/.test(ref)) throw new Error('pin a full commit SHA: --ref <sha>');
  const url = `https://raw.githubusercontent.com/${REPO}/${ref}/${SOURCE}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  const source = await res.text();
  const navUrl = `https://raw.githubusercontent.com/${REPO}/${ref}/${NAV_SOURCE}`;
  const navRes = await fetch(navUrl);
  if (!navRes.ok) throw new Error(`${navUrl}: ${navRes.status}`);
  const nav = navOutput(await navRes.text(), ref);
  const used = new Set([...usedTokens(readFileSync(USED_IN, 'utf8')), ...usedTokens(nav)]);
  const out = buildOutputs(source, ref, used);
  writeFileSync(CSS_OUT, out.css);
  writeFileSync(TS_OUT, out.ts);
  writeFileSync(NAV_OUT, nav);
  const icons: Record<string, string> = {};
  mkdirSync(NAV_ICON_OUT, { recursive: true });
  for (const id of NAV_ICON_IDS) {
    const iconUrl = `https://raw.githubusercontent.com/${REPO}/${ref}/${NAV_ICON_SOURCE}/${id}.webp`;
    const iconRes = await fetch(iconUrl);
    if (!iconRes.ok) throw new Error(`${iconUrl}: ${iconRes.status}`);
    const body = Buffer.from(await iconRes.arrayBuffer());
    if (body.subarray(0, 4).toString() !== 'RIFF' || body.subarray(8, 12).toString() !== 'WEBP') throw new Error(`${iconUrl}: not a WebP`);
    const file = `${NAV_ICON_OUT}/${id}.webp`;
    writeFileSync(file, body);
    icons[file] = sha256(body);
  }
  const street: Record<string, string> = {};
  const streetOut: Record<string, string> = {};
  for (const [kind, path] of Object.entries(STREET_SOURCES) as ['js' | 'dts' | 'css', string][]) {
    const r = await fetch(`https://raw.githubusercontent.com/${REPO}/${ref}/${path}`);
    if (!r.ok) throw new Error(`${path}@${ref}: ${r.status}`);
    const text = await r.text();
    const file = { js: STREET_JS_OUT, dts: STREET_DTS_OUT, css: STREET_CSS_OUT }[kind];
    const vendored = vendorStreetFile(text, path, ref, kind);
    writeFileSync(file, vendored);
    street[path] = sha256(text);
    streetOut[file] = sha256(vendored);
  }
  const next: Lock = {
    repo: REPO,
    ref,
    source: SOURCE,
    sourceSha256: sha256(source),
    street,
    outputs: { [CSS_OUT]: sha256(out.css), [TS_OUT]: sha256(out.ts), [NAV_OUT]: sha256(nav), ...icons, ...streetOut },
  };
  writeFileSync(LOCK, JSON.stringify(next, null, 2) + '\n');
  console.log(`wrote ${CSS_OUT} (${out.css.length} bytes), ${TS_OUT}, ${NAV_OUT}, the street module and ${LOCK}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  });
}
